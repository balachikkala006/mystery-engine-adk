"""Typed ADK FunctionTools managing case state, clues, notes, HITL confirmations, and verdicts.

Design principles aligned with AgentOps best practices:
- Comprehensive docstrings describing purpose, arguments, and return schemas.
- Strict Pydantic input/output JSON schema validation (`schemas.py`).
- Guided error responses with explicit `recovery_action` instructions back to the LLM.
- Human-in-the-Loop (HITL) confirmation hook (`tool_context.request_confirmation`)
  on high-stakes irreversible formal accusations (`submit_accusation`).
- Explicit ADK state scoping (`session`, `user:`, and `temp:`).
"""

from __future__ import annotations

import json
import logging
from typing import Any

from google.adk.tools.tool_context import ToolContext
from pydantic import ValidationError

from mystery_engine.cases import get_curated_case
from mystery_engine.config import get_settings
from mystery_engine.schemas import (
    AccusationInput,
    AccusationResult,
    CaseDossier,
    ClueInspectionOutput,
    InspectClueInput,
    InterrogationNoteInput,
    StartCaseInput,
)

logger = logging.getLogger(__name__)


def _guided_error(message: str, recovery_action: str, **extra: Any) -> dict[str, Any]:
    """Build a structured tool error with actionable recovery guidance for the LLM."""
    return {
        "status": "error",
        "message": message,
        "recovery_action": recovery_action,
        **extra,
    }


def compute_detective_rank(cases_solved: int) -> str:
    """Map total solved cases to a persistent detective rank stored in user-scoped state."""
    if cases_solved >= 5:
        return "Master Sleuth"
    if cases_solved >= 3:
        return "Chief Inspector"
    if cases_solved >= 1:
        return "Senior Detective"
    return "Rookie Investigator"


def start_new_case(
    theme: str = "noir",
    difficulty: str = "standard",
    custom_case_json: str = "",
    tool_context: ToolContext | None = None,
) -> dict[str, Any]:
    """Initialize a new mystery case dossier and persist it into ADK session state.

    Validates parameters against `StartCaseInput` and either parses a custom
    `CaseDossier` JSON generated by `CaseForgePipeline` or loads a curated starter case
    (`noir` or `scifi`). Resets per-case tracking fields while preserving cross-case
    `user:cases_solved` and `user:detective_rank`.

    Args:
        theme: Genre theme for the mystery (for example 'noir', 'scifi', or a custom theme).
        difficulty: Difficulty tier; must be one of 'easy', 'standard', or 'hard'.
        custom_case_json: Optional JSON string conforming to the `CaseDossier` schema.
            Leave empty to load a curated case matching `theme`.
        tool_context: ADK ToolContext automatically injected by the runtime.

    Returns:
        Dictionary with `status`, `message`, and player-safe `case` summary (never
        includes the sealed culprit or solution).
    """
    normalized_difficulty = difficulty.strip().lower()
    if normalized_difficulty not in {"easy", "standard", "hard"}:
        normalized_difficulty = "standard"

    try:
        validated = StartCaseInput(
            theme=theme or "noir",
            difficulty=normalized_difficulty,  # type: ignore[arg-type]
            custom_case_json=custom_case_json,
        )
    except ValidationError as exc:
        return _guided_error(
            message=f"Invalid start_new_case parameters: {exc.errors()[0]['msg']}",
            recovery_action=(
                "Retry start_new_case with a non-empty theme (e.g. 'noir' or 'scifi') "
                "and difficulty set to 'easy', 'standard', or 'hard'."
            ),
        )

    try:
        if validated.custom_case_json:
            payload = json.loads(validated.custom_case_json)
            dossier = CaseDossier.model_validate(payload)
        else:
            dossier = get_curated_case(theme=validated.theme)
            dossier.difficulty = validated.difficulty
    except Exception as exc:
        logger.warning("Invalid custom case payload; falling back to curated case: %s", exc)
        dossier = get_curated_case(theme=validated.theme)
        dossier.difficulty = validated.difficulty

    if tool_context is not None:
        settings = get_settings()
        tool_context.state["active_case"] = dossier.model_dump()
        tool_context.state["sealed_solution"] = dossier.solution.model_dump()
        tool_context.state["discovered_clues"] = []
        tool_context.state["interrogation_notes"] = []
        tool_context.state["accusation_attempts"] = 0
        tool_context.state["max_accusation_attempts"] = settings.max_accusation_attempts
        tool_context.state["case_solved"] = False
        tool_context.state["case_closed"] = False
        tool_context.state["memory_synced"] = False
        tool_context.state["user:favorite_theme"] = dossier.theme
        solved = int(tool_context.state.get("user:cases_solved", 0))
        tool_context.state["user:cases_solved"] = solved
        tool_context.state["user:detective_rank"] = compute_detective_rank(solved)

    return {
        "status": "success",
        "message": f"Case '{dossier.title}' initialized.",
        "case": dossier.public_summary(),
    }


def inspect_clue(clue_id: str, tool_context: ToolContext) -> dict[str, Any]:
    """Examine a specific crime-scene clue to unlock hidden forensic evidence.

    Validates `clue_id` using `InspectClueInput`, marks the clue discovered in session
    state, and returns a strict `ClueInspectionOutput` payload including any
    `fingerprint_sample` or `cipher_text` that can be forwarded to the MCP Forensics Lab.

    Args:
        clue_id: Identifier of the clue to examine (for example 'clue_1', 'clue_2').
        tool_context: ADK ToolContext holding the active case session state.

    Returns:
        Validated `ClueInspectionOutput` dict on success, or a guided error dict
        listing `available_clue_ids` and a `recovery_action` on failure.
    """
    try:
        validated = InspectClueInput(clue_id=clue_id)
    except ValidationError:
        return _guided_error(
            message="Clue identifier cannot be empty.",
            recovery_action="Call list_case_status to view valid clue IDs, then retry inspect_clue.",
        )

    raw_case = tool_context.state.get("active_case")
    if not raw_case:
        return _guided_error(
            message="No active case found in the current session.",
            recovery_action="Call start_new_case(theme='noir') before attempting to inspect clues.",
        )

    dossier = CaseDossier.model_validate(raw_case)
    normalized_id = validated.clue_id.lower()
    matched = next((c for c in dossier.clues if c.clue_id.lower() == normalized_id), None)

    if matched is None:
        available = [c.clue_id for c in dossier.clues]
        return _guided_error(
            message=f"Clue '{validated.clue_id}' does not exist in this case.",
            recovery_action=f"Ask the detective to pick a valid clue ID from {available} and retry inspect_clue.",
            available_clue_ids=available,
        )

    discovered: list[str] = list(tool_context.state.get("discovered_clues", []))
    already_inspected = matched.clue_id in discovered
    if not already_inspected:
        discovered.append(matched.clue_id)
        tool_context.state["discovered_clues"] = discovered

    output = ClueInspectionOutput(
        already_inspected=already_inspected,
        clue_id=matched.clue_id,
        title=matched.title,
        location=matched.location,
        surface_description=matched.surface_description,
        forensic_detail=matched.forensic_detail,
        fingerprint_sample=matched.fingerprint_sample,
        cipher_text=matched.cipher_text,
        total_discovered=len(discovered),
        total_clues=len(dossier.clues),
    )
    return output.model_dump()


def record_interrogation_note(
    suspect_name: str,
    summary: str,
    contradiction_spotted: bool = False,
    tool_context: ToolContext | None = None,
) -> dict[str, Any]:
    """Persist a structured interrogation observation into the active case notebook.

    Validates arguments with `InterrogationNoteInput` and appends the note to
    `tool_context.state["interrogation_notes"]` so future turns and agents can cross-check
    suspect statements against physical clues.

    Args:
        suspect_name: Full name of the suspect who made the statement.
        summary: Concise summary of the claim, reaction, or alibi detail (3-500 chars).
        contradiction_spotted: Set True when testimony contradicts verified forensic evidence.
        tool_context: ADK ToolContext automatically injected by the runtime.

    Returns:
        Dictionary confirming the saved note and updated `total_notes` count, or a guided
        error dict with `recovery_action`.
    """
    if tool_context is None or not tool_context.state.get("active_case"):
        return _guided_error(
            message="No active case found. Cannot record interrogation notes.",
            recovery_action="Start a mystery case with start_new_case before interrogating suspects.",
        )

    try:
        validated = InterrogationNoteInput(
            suspect_name=suspect_name,
            summary=summary,
            contradiction_spotted=contradiction_spotted,
        )
    except ValidationError as exc:
        return _guided_error(
            message=f"Invalid interrogation note: {exc.errors()[0]['msg']}",
            recovery_action=(
                "Provide a non-empty suspect_name and a clear summary of at least 3 characters."
            ),
        )

    notes: list[dict[str, Any]] = list(tool_context.state.get("interrogation_notes", []))
    entry = validated.model_dump()
    notes.append(entry)
    tool_context.state["interrogation_notes"] = notes

    return {
        "status": "success",
        "note_saved": entry,
        "total_notes": len(notes),
    }


def list_case_status(tool_context: ToolContext) -> dict[str, Any]:
    """Retrieve a player-safe snapshot of investigation progress and detective rank.

    Inspects both session-scoped investigation state (`active_case`, `discovered_clues`,
    `interrogation_notes`, `accusation_attempts`) and user-scoped persistent progression
    (`user:cases_solved`, `user:detective_rank`).

    Args:
        tool_context: ADK ToolContext holding session and user-scoped state.

    Returns:
        Structured dictionary summarizing discovered vs. undiscovered clues, suspects,
        interrogation notes, remaining accusation attempts, and detective rank.
    """
    raw_case = tool_context.state.get("active_case")
    cases_solved = int(tool_context.state.get("user:cases_solved", 0))
    rank = tool_context.state.get("user:detective_rank") or compute_detective_rank(cases_solved)

    if not raw_case:
        return {
            "status": "success",
            "has_active_case": False,
            "detective_rank": rank,
            "cases_solved": cases_solved,
            "message": "No active case yet. Ask to start a noir, scifi, or custom mystery.",
        }

    dossier = CaseDossier.model_validate(raw_case)
    discovered = list(tool_context.state.get("discovered_clues", []))
    notes = list(tool_context.state.get("interrogation_notes", []))
    attempts = int(tool_context.state.get("accusation_attempts", 0))
    max_attempts = int(tool_context.state.get("max_accusation_attempts", 2))

    return {
        "status": "success",
        "has_active_case": True,
        "case_id": dossier.case_id,
        "title": dossier.title,
        "theme": dossier.theme,
        "case_solved": bool(tool_context.state.get("case_solved", False)),
        "case_closed": bool(tool_context.state.get("case_closed", False)),
        "suspects": [s.name for s in dossier.suspects],
        "discovered_clues": discovered,
        "undiscovered_clues": [c.clue_id for c in dossier.clues if c.clue_id not in discovered],
        "interrogation_notes": notes,
        "attempts_remaining": max(0, max_attempts - attempts),
        "detective_rank": rank,
        "cases_solved": cases_solved,
    }


def submit_accusation(
    suspect_name: str,
    motive: str,
    key_evidence_ids: list[str],
    tool_context: ToolContext,
    confirmed_by_detective: bool = False,
) -> dict[str, Any]:
    """File a high-stakes formal arrest/accusation with Human-in-the-Loop confirmation.

    Because filing a formal accusation consumes a limited attempt and can permanently
    close the case, this tool enforces an explicit Human-in-the-Loop (HITL) stop:
    - If neither `tool_context.tool_confirmation` nor `confirmed_by_detective=True` is
      present, it invokes ADK's `tool_context.request_confirmation(...)` (when running
      inside an ADK invocation) and returns `status="pending_confirmation"` so the human
      detective can approve or cancel before execution.
    - If the human rejects the confirmation, the arrest is aborted cleanly without
      spending an attempt.
    - Once confirmed, evaluates the accusation deterministically against the sealed truth.

    Args:
        suspect_name: Exact name of the suspect being formally accused.
        motive: Explanation of why the accused committed the crime.
        key_evidence_ids: List of clue IDs (for example ['clue_1', 'clue_2']) backing the charge.
        tool_context: ADK ToolContext holding state and ADK HITL confirmation metadata.
        confirmed_by_detective: Set True ONLY after the human detective explicitly confirms
            they want to lock in this formal accusation.

    Returns:
        Dictionary containing either `status="pending_confirmation"` (HITL pause),
        `status="cancelled"` (human rejected), a guided error with `recovery_action`,
        or the final `AccusationResult` (`solved`, `wrong_suspect`, or `case_failed`).
    """
    raw_case = tool_context.state.get("active_case")
    if not raw_case:
        return _guided_error(
            message="No active case to judge.",
            recovery_action="Call start_new_case first so the detective has a case to solve.",
        )

    if tool_context.state.get("case_closed"):
        return _guided_error(
            message="This case is already closed and cannot accept new accusations.",
            recovery_action="Invite the detective to start a new case via start_new_case.",
        )

    try:
        validated = AccusationInput(
            suspect_name=suspect_name,
            motive=motive,
            key_evidence_ids=key_evidence_ids,
            confirmed_by_detective=confirmed_by_detective,
        )
    except ValidationError as exc:
        return _guided_error(
            message=f"Invalid accusation payload: {exc.errors()[0]['msg']}",
            recovery_action=(
                "Ask the detective to specify both the suspect's name and a clear motive "
                "(at least 3 characters) before calling submit_accusation."
            ),
        )

    # ------------------------------------------------------------------
    # Human-in-the-Loop (HITL) Confirmation Gate for High-Stakes Arrest
    # ------------------------------------------------------------------
    tool_confirmation = getattr(tool_context, "tool_confirmation", None)
    if tool_confirmation is not None:
        if not tool_confirmation.confirmed:
            return {
                "status": "cancelled",
                "message": (
                    f"Formal accusation against {validated.suspect_name} was cancelled by "
                    "the detective. No accusation attempts were spent."
                ),
                "recovery_action": (
                    "Ask the detective what clue or suspect they would like to investigate next."
                ),
            }
    elif not validated.confirmed_by_detective:
        attempts_used = int(tool_context.state.get("accusation_attempts", 0))
        max_attempts = int(tool_context.state.get("max_accusation_attempts", 2))
        remaining = max(0, max_attempts - attempts_used)
        confirmation_hint = (
            f"Confirm formal arrest warrant against '{validated.suspect_name}' citing "
            f"{validated.key_evidence_ids or ['no specific clues']}? "
            f"You have {remaining} attempt(s) remaining and this action is high-stakes."
        )
        confirmation_payload = {
            "action": "formal_arrest_accusation",
            "suspect_name": validated.suspect_name,
            "motive": validated.motive,
            "key_evidence_ids": validated.key_evidence_ids,
            "attempts_remaining": remaining,
        }
        request_fn = getattr(tool_context, "request_confirmation", None)
        if callable(request_fn) and getattr(tool_context, "function_call_id", None):
            request_fn(hint=confirmation_hint, payload=confirmation_payload)
        tool_context.state["temp:pending_accusation"] = confirmation_payload
        return {
            "status": "pending_confirmation",
            "requires_human_confirmation": True,
            "message": confirmation_hint,
            "pending_accusation": confirmation_payload,
            "recovery_action": (
                "Pause and ask the human detective to explicitly confirm or cancel this "
                "formal accusation. Once confirmed, call submit_accusation with "
                "confirmed_by_detective=True."
            ),
        }

    dossier = CaseDossier.model_validate(raw_case)
    solution = dossier.solution
    attempts = int(tool_context.state.get("accusation_attempts", 0)) + 1
    max_attempts = int(tool_context.state.get("max_accusation_attempts", 2))
    tool_context.state["accusation_attempts"] = attempts
    tool_context.state["temp:pending_accusation"] = None
    attempts_remaining = max(0, max_attempts - attempts)

    accused_norm = validated.suspect_name.lower()
    culprit_norm = solution.culprit_name.strip().lower()
    is_correct_culprit = accused_norm == culprit_norm or culprit_norm in accused_norm

    cited = {cid.lower() for cid in validated.key_evidence_ids}
    required = {cid.strip().lower() for cid in solution.key_clue_ids}
    matched_evidence = len(cited & required)
    evidence_ratio = matched_evidence / max(1, len(required))

    motive_tokens = {w.strip(".,!?;:").lower() for w in validated.motive.split() if len(w) > 3}
    truth_tokens = {w.strip(".,!?;:").lower() for w in solution.true_motive.split() if len(w) > 3}
    motive_overlap = len(motive_tokens & truth_tokens)
    motive_bonus = 20 if motive_overlap >= 2 else (10 if motive_overlap == 1 else 0)

    if is_correct_culprit:
        score = min(100, int(50 + round(30 * evidence_ratio) + motive_bonus))
        tool_context.state["case_solved"] = True
        tool_context.state["case_closed"] = True
        cases_solved = int(tool_context.state.get("user:cases_solved", 0)) + 1
        new_rank = compute_detective_rank(cases_solved)
        tool_context.state["user:cases_solved"] = cases_solved
        tool_context.state["user:detective_rank"] = new_rank

        result = AccusationResult(
            verdict="solved",
            score=score,
            attempts_remaining=attempts_remaining,
            feedback=(
                f"Case solved! You accurately identified {solution.culprit_name} with "
                f"{matched_evidence}/{len(required)} key evidence items."
            ),
            revealed_solution=solution,
        )
        return {
            "status": "success",
            **result.model_dump(),
            "detective_rank": new_rank,
            "cases_solved": cases_solved,
        }

    if attempts_remaining == 0:
        tool_context.state["case_solved"] = False
        tool_context.state["case_closed"] = True
        result = AccusationResult(
            verdict="case_failed",
            score=int(round(20 * evidence_ratio)),
            attempts_remaining=0,
            feedback=(
                f"Incorrect accusation ({validated.suspect_name}). No attempts left—the true "
                f"culprit was {solution.culprit_name}."
            ),
            revealed_solution=solution,
        )
        return {"status": "success", **result.model_dump()}

    result = AccusationResult(
        verdict="wrong_suspect",
        score=0,
        attempts_remaining=attempts_remaining,
        feedback=(
            f"The evidence does not convict {validated.suspect_name}. Re-examine the forensic "
            f"lab findings and alibi timelines ({attempts_remaining} attempt remaining)."
        ),
        revealed_solution=None,
    )
    return {"status": "success", **result.model_dump()}


def exit_refinement_loop(approval_summary: str, tool_context: ToolContext) -> dict[str, Any]:
    """Terminate the ADK LoopAgent once custom case lore passes consistency review.

    Sets `tool_context.actions.escalate = True` and records the approval summary in
    temporary state (`temp:lore_approved`).

    Args:
        approval_summary: Short confirmation explaining why clues, alibis, and
            the culprit timeline are logically airtight.
        tool_context: ADK ToolContext whose `actions.escalate` flag stops the loop.

    Returns:
        Dictionary confirming loop escalation and approval summary.
    """
    summary = approval_summary.strip()
    if not summary:
        return _guided_error(
            message="approval_summary cannot be empty when exiting the refinement loop.",
            recovery_action="Provide a one-sentence confirmation summarizing the verified lore.",
        )

    tool_context.state["temp:lore_approved"] = True
    tool_context.state["temp:lore_approval_summary"] = summary
    tool_context.actions.escalate = True
    return {
        "status": "success",
        "escalated": True,
        "approval_summary": summary,
    }
